const form = document.getElementById("checkout-form");
const langButton = document.getElementById("lang-toggle");
const paymentHint = document.getElementById("payment-hint");
let currentLang = localStorage.getItem("artinatur-lang") || "es";

const paymentHintKeys = { yappy: "hintYappy", cash_on_delivery: "hintCash" };

function renderText() {
  const copy = translations[currentLang];
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = copy[node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const value = copy[node.dataset.i18nAria];
    if (value) node.setAttribute("aria-label", value);
  });
  document.documentElement.lang = currentLang;
  langButton.textContent = currentLang === "es" ? "EN" : "ES";
  paymentHint.textContent = copy[paymentHintKeys[form.payment.value]];
}

langButton.addEventListener("click", () => {
  currentLang = currentLang === "es" ? "en" : "es";
  localStorage.setItem("artinatur-lang", currentLang);
  renderText();
});

form.addEventListener("change", (event) => {
  if (event.target.name === "payment") paymentHint.textContent = translations[currentLang][paymentHintKeys[event.target.value]];
});

function openTestimonial(button) {
  const previousFocus = document.activeElement;
  const sourceImage = button.querySelector("img");
  const lightbox = document.createElement("div");
  lightbox.className = "testimonial-lightbox";
  lightbox.setAttribute("role", "dialog");
  lightbox.setAttribute("aria-modal", "true");
  lightbox.setAttribute("aria-label", translations[currentLang].openTestimonial);
  lightbox.innerHTML = `
    <div class="testimonial-lightbox-content">
      <button class="testimonial-lightbox-close" type="button" aria-label="${translations[currentLang].closeTestimonial}">
        <svg aria-hidden="true" width="24" height="24" viewBox="0 0 24 24" fill="none"><path d="M6 6l12 12M18 6L6 18" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>
      </button>
      <img src="${button.dataset.testimonialSrc}" alt="${sourceImage.alt}" />
    </div>`;

  const closeButton = lightbox.querySelector(".testimonial-lightbox-close");
  const closeLightbox = () => {
    document.removeEventListener("keydown", handleKeydown);
    document.body.classList.remove("lightbox-open");
    lightbox.remove();
    previousFocus?.focus();
  };
  const handleKeydown = (event) => {
    if (event.key === "Escape") closeLightbox();
    if (event.key === "Tab") {
      event.preventDefault();
      closeButton.focus();
    }
  };

  closeButton.addEventListener("click", closeLightbox);
  lightbox.addEventListener("click", (event) => { if (event.target === lightbox) closeLightbox(); });
  document.addEventListener("keydown", handleKeydown);
  document.body.classList.add("lightbox-open");
  document.body.appendChild(lightbox);
  closeButton.focus();
}

document.querySelectorAll(".testimonial-card").forEach((button) => {
  button.addEventListener("click", () => openTestimonial(button));
});

renderText();
